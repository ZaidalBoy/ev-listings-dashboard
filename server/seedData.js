function isoHoursAgo(hours) {
  return new Date(Date.now() - hours * 3600 * 1000).toISOString();
}

function isoDaysAgo(days) {
  return new Date(Date.now() - days * 86400 * 1000).toISOString();
}

export function fallbackImageForBodyStyle(bodyStyle = '', model = '') {
  const b = `${bodyStyle} ${model}`.toLowerCase();
  if (b.includes('truck') || b.includes('pickup') || b.includes('r1t') || b.includes('lightning') || b.includes('cybertruck')) {
    return '/images/ev_truck_slate.jpg';
  }
  if (
    b.includes('suv') ||
    b.includes('crossover') ||
    b.includes('utility') ||
    b.includes('model y') ||
    b.includes('model x') ||
    b.includes('ioniq 5') ||
    b.includes('ev6') ||
    b.includes('ev9') ||
    b.includes('mach-e') ||
    b.includes('r1s') ||
    b.includes('equinox') ||
    b.includes('blazer') ||
    b.includes('id.4') ||
    b.includes('lyriq') ||
    b.includes('ix') ||
    b.includes('ex30')
  ) {
    return '/images/ev_suv_emerald.jpg';
  }
  return '/images/ev_sedan_silver.jpg';
}

